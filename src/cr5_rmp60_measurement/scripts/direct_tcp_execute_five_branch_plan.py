def validate_args(args) -> None:
    if args.speed < 1 or args.speed > 5:
        raise ValueError("--speed must be between 1 and 5")
    if args.timeout_sec <= 0 or args.positioning_timeout_sec <= 0:
        raise ValueError("timeouts must be positive")
    if args.position_tolerance_mm <= 0 or args.orientation_tolerance_deg <= 0:
        raise ValueError("pose tolerances must be positive")
    if args.poll_interval_sec <= 0:
        raise ValueError("--poll-interval-sec must be positive")
    if min(args.max_entry_pos_mm, args.max_entry_orientation_deg, args.max_entry_joint_deg) <= 0:
        raise ValueError("entry tolerances must be positive")
    if args.execute and not args.ack_direct_dobot_tcp_probing:
        raise ValueError("real robot motion requires --ack-direct-dobot-tcp-probing")
    if args.output.exists() and not args.resume and args.execute:
        raise ValueError(f"{args.output} already exists; use --resume or choose a new output")


def validate_sphere_motion_mode(items, args):
    from sphere_contact_safety import requires_sphere_safety
    if not args.execute or not any(requires_sphere_safety(item["row"]) for item in items):
        return
    raise ValueError("新版标准球路径必须通过 verified_sphere_executor.py 执行已验证关节轨迹；禁止替换成端点 MovL/MovJ")


def main() -> None:
    args = parse_args()
    validate_args(args)
    plan = load_plan(args.plan)
    items = selected_items(plan, args)
    validate_sphere_motion_mode(items, args)
    if not items:
        raise SystemExit("no plan rows selected")
    print(f"loaded plan rows: {len(plan)}; selected rows: {len(items)}", flush=True)
    print(f"output: {args.output}", flush=True)

    if not args.execute:
        for item in items:
            execute_item(None, None, args, item)  # type: ignore[arg-type]
        print("dry-run complete; add --execute --ack-direct-dobot-tcp-probing for real motion", flush=True)
        return

    feedback = FeedbackReader(args.ip)
    dashboard = Dashboard(args.ip, timeout=args.command_timeout_sec)
    feedback.start()
    counts = {"HIT": 0, "MISS": 0, "EARLY": 0}
    try:
        check_initial_robot_state(dashboard, feedback, args)
        if args.check_only:
            print("check-only complete; no motion commanded", flush=True)
            return
        for item in items:
            status = execute_item(dashboard, feedback, args, item)
            if status == "HIT":
                counts["HIT"] += 1
            elif status == "MISS":
                counts["MISS"] += 1
            elif status.startswith("EARLY_TRIGGER"):
                counts["EARLY"] += 1
                if not args.resume:
                    raise RuntimeError(f"{item['plan_id']} ended with {status}; stopping run for review")
        print(
            f"\nexecution complete: HIT={counts['HIT']} MISS={counts['MISS']} EARLY={counts['EARLY']}",
            flush=True,
        )
    except BaseException:
        try:
            dashboard.stop()
        except Exception:
            pass
        raise
    finally:
        dashboard.close()
        feedback.close()


if __name__ == "__main__":
    main()
