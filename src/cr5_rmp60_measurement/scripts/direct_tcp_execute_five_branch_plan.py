"""Execute a five-branch standard-sphere probing plan through Dobot TCP.

This is a fallback executor for cases where the ROS2 Dobot service layer is
connected but service calls hang.  It uses:

- port 29999 (Dashboard) for MovJ/MovL/Stop/SpeedFactor commands;
- port 30004 (Feedback) for DI1, flange pose, and joint snapshots.

The input plan must already contain flange-level safe/transition/start/target
poses, as generated by plan_compensation_dataset.py or
auto_calibrate_five_branch_sphere.py.  The output contact CSV is intentionally
compatible with auto_calibrate_five_branch_sphere.py --fit-only.
"""

