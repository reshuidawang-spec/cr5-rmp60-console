FEEDBACK_FRAME_BYTES = 1440
DI_BITS_OFFSET = 8
ROBOT_MODE_OFFSET = 24
CONTROLLER_TIMER_OFFSET = 32
Q_ACTUAL_OFFSET = 432
TOOL_VECTOR_ACTUAL_OFFSET = 624


class DobotCommandError(RuntimeError):
    """Dashboard command failed."""


class FeedbackReader:
    """Background reader for CR5 port 30004 feedback frames."""

    def __init__(self, ip: str, port: int = 30004, timeout: float = 3.0):
        self.ip = ip
        self.port = port
        self.timeout = timeout
        self._lock = threading.Lock()
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self._snapshot: dict | None = None
        self._error: str | None = None
        self._sequence = 0
        self._trigger_events = deque(maxlen=128)

    def start(self) -> None:
        self._thread = threading.Thread(target=self._run, daemon=True)
        self._thread.start()

    def close(self) -> None:
        self._stop.set()
        if self._thread is not None:
            self._thread.join(timeout=2.0)

    def _read_exact(self, sock: socket.socket, size: int) -> bytes:
        chunks = []
        remaining = size
        while remaining > 0 and not self._stop.is_set():
            chunk = sock.recv(remaining)
            if not chunk:
                raise OSError("feedback socket closed")
            chunks.append(chunk)
            remaining -= len(chunk)
        return b"".join(chunks)

    def _run(self) -> None:
        while not self._stop.is_set():
            try:
                with socket.create_connection((self.ip, self.port), timeout=self.timeout) as sock:
                    sock.settimeout(self.timeout)
                    while not self._stop.is_set():
                        raw = self._read_exact(sock, FEEDBACK_FRAME_BYTES)
                        if len(raw) != FEEDBACK_FRAME_BYTES:
                            raise OSError(f"incomplete feedback frame: {len(raw)} bytes")
                        frame_len = struct.unpack("<H", raw[0:2])[0]
                        if frame_len != FEEDBACK_FRAME_BYTES:
                            raise OSError(f"unexpected feedback frame length field: {frame_len}")
                        self._sequence += 1
                        bits = struct.unpack("<Q", raw[DI_BITS_OFFSET : DI_BITS_OFFSET + 8])[0]
                        robot_mode = struct.unpack("<Q", raw[ROBOT_MODE_OFFSET : ROBOT_MODE_OFFSET + 8])[0]
                        timer = struct.unpack(
                            "<Q", raw[CONTROLLER_TIMER_OFFSET : CONTROLLER_TIMER_OFFSET + 8]
                        )[0]
                        joints = list(struct.unpack("<6d", raw[Q_ACTUAL_OFFSET : Q_ACTUAL_OFFSET + 48]))
                        pose = list(
                            struct.unpack(
                                "<6d",
                                raw[TOOL_VECTOR_ACTUAL_OFFSET : TOOL_VECTOR_ACTUAL_OFFSET + 48],
                            )
                        )
                        snapshot = {
                            "sequence": self._sequence,
                            "monotonic_time": time.monotonic(),
                            "wall_time": time.time(),
                            "controller_timer": timer,
                            "digital_input_bits": int(bits),
                            "di1": bool(bits & 0x01),
                            "robot_mode": int(robot_mode),
                            "pose": pose,
                            "joints": joints,
                        }
                        with self._lock:
                            if snapshot["di1"] and (self._snapshot is None or not self._snapshot["di1"]):
                                self._trigger_events.append(dict(snapshot))
                            self._snapshot = snapshot
                            self._error = None
            except OSError as exc:
                with self._lock:
                    self._error = str(exc)
                if not self._stop.is_set():
                    time.sleep(0.2)

    def snapshot(self, max_age_sec: float = 0.5) -> dict:
        with self._lock:
            snapshot = None if self._snapshot is None else dict(self._snapshot)
            error = self._error
        if snapshot is None:
            raise RuntimeError(f"no feedback frame yet" + (f": {error}" if error else ""))
        age = time.monotonic() - float(snapshot["monotonic_time"])
        if age > max_age_sec:
            raise RuntimeError(f"feedback frame is stale ({age:.3f}s)" + (f": {error}" if error else ""))
        return snapshot

    def trigger_since(self, sequence: int):
        """Retain DI rising-edge frames even if a later frame has already released."""
        with self._lock:
            return next((dict(item) for item in self._trigger_events if item["sequence"] > sequence), None)

    def wait_fresh(self, timeout_sec: float = 5.0) -> dict:
        deadline = time.monotonic() + timeout_sec
        while time.monotonic() < deadline:
            try:
                return self.snapshot(max_age_sec=0.5)
            except RuntimeError:
                time.sleep(0.02)
        return self.snapshot(max_age_sec=0.5)


class Dashboard:
    """Persistent Dobot Dashboard client."""

    def __init__(self, ip: str, port: int = 29999, timeout: float = 3.0):
        self.ip = ip
        self.port = port
        self.timeout = timeout
        self._sock: socket.socket | None = None

    def close(self) -> None:
        if self._sock is not None:
            try:
                self._sock.close()
            finally:
                self._sock = None

    def _connect(self, timeout: float) -> socket.socket:
        if self._sock is None:
            self._sock = socket.create_connection((self.ip, self.port), timeout=timeout)
        self._sock.settimeout(timeout)
        return self._sock

    def command(
        self,
        command: str,
        timeout: float | None = None,
        expect_zero: bool = True,
        allow_empty: bool = False,
    ) -> str:
        timeout = self.timeout if timeout is None else timeout
        last_reply = ""
        for attempt in range(3):
            try:
                sock = self._connect(timeout)
                sock.sendall((command + "\n").encode("ascii"))
                chunks = []
                deadline = time.monotonic() + timeout
                while time.monotonic() < deadline:
                    try:
                        chunk = sock.recv(4096)
                    except socket.timeout:
                        continue
                    if not chunk:
                        break
                    chunks.append(chunk)
                    if b";" in chunk:
                        break
                reply = b"".join(chunks).decode("ascii", errors="replace").strip()
                last_reply = reply
                if "port has been occupied" in reply.lower() or "connection refused" in reply.lower():
                    self.close()
                    time.sleep(0.2 + 0.2 * attempt)
                    continue
                break
            except OSError as exc:
                self.close()
                last_reply = str(exc)
                if attempt == 2:
                    raise
                time.sleep(0.2 + 0.2 * attempt)
        else:
            reply = last_reply
        if not reply and allow_empty:
            return reply
        if not reply:
            raise DobotCommandError(f"{command}: empty dashboard reply")
        if expect_zero:
            code = parse_reply_code(reply)
            if code != 0:
                raise DobotCommandError(f"{command}: dashboard returned {code}: {reply}")
        return reply

    def stop(self) -> None:
        for attempt in range(2):
            try:
                self.command("Stop()", timeout=1.0, expect_zero=False)
                return
            except (OSError, DobotCommandError):
                if attempt == 1:
                    raise
                time.sleep(0.02)


def parse_reply_code(reply: str) -> int:
    match = re.match(r"\s*(-?\d+)\s*,", reply)
    if not match:
        raise DobotCommandError(f"cannot parse dashboard result code: {reply}")
    return int(match.group(1))


def parse_reply_values(reply: str) -> list[str]:
    match = re.search(r"\{([^}]*)\}", reply)
    if not match:
        return []
    text = match.group(1).strip()
    if not text:
        return []
    return [part.strip() for part in text.split(",")]


def pose_command(command_name: str, pose: list[float]) -> str:
    # Match dobot_bringup_v4 parseTool.cpp exactly: {%0.3f,...}.
    values = ",".join(f"{float(value):.3f}" for value in pose)
    return f"{command_name}(pose={{{values}}})"


def angle_delta_deg(actual: float, expected: float) -> float:
    return (float(actual) - float(expected) + 180.0) % 360.0 - 180.0


def pose_errors(actual: list[float], expected: list[float]) -> tuple[float, float]:
    position = math.sqrt(sum((float(actual[index]) - float(expected[index])) ** 2 for index in range(3)))
    orientation = max(abs(angle_delta_deg(actual[index], expected[index])) for index in range(3, 6))
    return position, orientation


def pose_reached(
    actual: list[float],
    expected: list[float],
    position_tolerance_mm: float,
    orientation_tolerance_deg: float,
) -> bool:
    position, orientation = pose_errors(actual, expected)
    return position <= position_tolerance_mm and orientation <= orientation_tolerance_deg


def pose_fields(prefix: str, pose: list[float] | None) -> dict[str, str]:
    return {
        f"{prefix}_{name}": "" if pose is None else f"{float(pose[index]):.4f}"
        for index, name in enumerate(POSE_NAMES)
    }


def vector_fields(prefix: str, values: list[float] | None, count: int, digits: int = 6) -> dict[str, str]:
    return {
        f"{prefix}_{index + 1}": "" if values is None or index >= len(values) else f"{float(values[index]):.{digits}f}"
        for index in range(count)
    }


def row_pose(row: dict[str, str], prefix: str) -> list[float]:
    return [float(row[f"{prefix}_{name}"]) for name in POSE_NAMES]


def load_plan(path: Path) -> list[dict]:
    with path.open(newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError(f"{path}: empty plan")
    from sphere_contact_safety import requires_sphere_safety, validate_safety_receipt
    seen = set()
    items = []
    for row_index, row in enumerate(rows, start=1):
        plan_id = row.get("plan_id") or f"row_{row_index}"
        if plan_id in seen:
            raise ValueError(f"{path}: duplicate plan_id {plan_id}")
        seen.add(plan_id)
        if requires_sphere_safety(row):
            validate_safety_receipt(row)
        for prefix in ("safe_flange", "transition_flange", "start_flange", "target_flange"):
            missing = [f"{prefix}_{name}" for name in POSE_NAMES if row.get(f"{prefix}_{name}") in ("", None)]
            if missing:
                raise ValueError(f"{plan_id}: missing {', '.join(missing)}")
        if row.get("probe_collision_status") != "OK":
            raise ValueError(
                f"{plan_id}: probe_collision_status={row.get('probe_collision_status')} "
                f"clearance={row.get('min_probe_clearance_mm')}"
            )
        items.append(
            {
                "row": row,
                "plan_id": plan_id,
                "branch": row.get("branch", ""),
                "safe_pose": row_pose(row, "safe_flange"),
                "transition_pose": row_pose(row, "transition_flange"),
                "start_pose": row_pose(row, "start_flange"),
                "target_pose": row_pose(row, "target_flange"),
            }
        )
    return items


def existing_plan_ids(path: Path) -> set[str]:
    if not path.exists():
        return set()
    with path.open(newline="") as f:
        return {row.get("plan_id", "") for row in csv.DictReader(f) if row.get("plan_id")}


def append_stable_row(path: Path, row: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    exists = path.exists()
    if exists:
        with path.open(newline="") as f:
            header = next(csv.reader(f), None)
        if header != list(row.keys()):
            raise ValueError(f"CSV header mismatch for {path}; choose a new --output")
    with path.open("a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(row.keys()))
        if not exists:
            writer.writeheader()
        writer.writerow(row)


def contact_row(args, item: dict, status: str, trigger: dict | None, stop_snapshot: dict | None) -> dict[str, str]:
    row = item["row"]
    trigger_pose = None if trigger is None else trigger.get("pose")
    stop_pose = None if stop_snapshot is None else stop_snapshot.get("pose")
    result = {
        "timestamp": f"{time.time():.3f}",
        "plan_id": item["plan_id"],
        "status": status,
        "session_id": args.session_id,
        "workpiece_id": args.workpiece_id,
        "artifact_id": args.artifact_id,
        "artifact_type": args.artifact_type,
        "standard_sphere_id": str(row.get("standard_sphere_id", "")),
        "physical_ball_id": str(row.get("physical_ball_id") or args.physical_ball_id),
        "branch": item["branch"],
        "operator_note": args.operator_note,
        "reference_fit_json": str(args.reference_fit_json),
        "euler_sequence": row.get("euler_sequence") or args.euler_sequence,
        "approach_x": f"{float(row['approach_x']):.6f}",
        "approach_y": f"{float(row['approach_y']):.6f}",
        "approach_z": f"{float(row['approach_z']):.6f}",
        "sphere_center_x": f"{float(row['sphere_center_x']):.6f}",
        "sphere_center_y": f"{float(row['sphere_center_y']):.6f}",
        "sphere_center_z": f"{float(row['sphere_center_z']):.6f}",
        "contact_center_distance_mm": f"{float(row['contact_center_distance_mm']):.6f}",
        "trigger_feed_sequence": "" if trigger is None else str(trigger.get("sequence", "")),
        "trigger_feed_wall_time": "" if trigger is None else f"{float(trigger.get('wall_time', 0.0)):.6f}",
        "trigger_digital_input_bits": "" if trigger is None else str(trigger.get("digital_input_bits", "")),
        "trigger_di1": "" if trigger is None else str(int(bool(trigger.get("di1", False)))),
    }
    for field in PLAN_METADATA_FIELDS:
        result[field] = str(row.get(field, ""))
    result.update(pose_fields("start_flange", item["start_pose"]))
    result.update(pose_fields("target_flange", item["target_pose"]))
    result.update(pose_fields("trigger_flange", trigger_pose))
    result.update(pose_fields("stop_flange", stop_pose))
    result.update(vector_fields("trigger_joint", None if trigger is None else trigger.get("joints"), 6))
    return result


def check_initial_robot_state(dashboard: Dashboard, feedback: FeedbackReader, args) -> None:
    snapshot = feedback.wait_fresh(args.feedback_start_timeout_sec)
    if snapshot["di1"]:
        raise RuntimeError("DI1 is already triggered before probing; retract or clear the probe first")
    expected_entry_pose = getattr(args, "expected_entry_pose", None)
    expected_entry_joints = getattr(args, "expected_entry_joints", None)
    if expected_entry_pose is not None:
        position_error = math.dist(snapshot["pose"][:3], expected_entry_pose[:3])
        orientation_error = max(
            abs((actual - expected + 180.0) % 360.0 - 180.0)
            for actual, expected in zip(snapshot["pose"][3:], expected_entry_pose[3:])
        )
        if position_error > getattr(args, "max_entry_pos_mm", 0.15) or orientation_error > getattr(args, "max_entry_orientation_deg", 0.2):
            raise RuntimeError(
                "robot moved after current-state entry preflight: "
                f"position={position_error:.3f} mm, orientation={orientation_error:.3f} deg"
            )
    if expected_entry_joints is not None:
        joint_error = max(
            abs((actual - expected + 180.0) % 360.0 - 180.0)
            for actual, expected in zip(snapshot["joints"], expected_entry_joints)
        )
        if joint_error > getattr(args, "max_entry_joint_deg", 0.2):
            raise RuntimeError(f"robot joints moved after entry preflight: {joint_error:.3f} deg")
    robot_mode = snapshot.get("robot_mode")
    print(
        "feedback ready: "
        f"pose={format_pose(snapshot['pose'])} "
        f"DI1={int(snapshot['di1'])} robot_mode={robot_mode}",
        flush=True,
    )
    try:
        mode_reply = dashboard.command("RobotMode()", timeout=1.5, expect_zero=True)
        print(f"RobotMode(): {mode_reply}", flush=True)
        print(f"DI(1): {dashboard.command('DI(1)', timeout=1.5, expect_zero=True)}", flush=True)
    except (OSError, DobotCommandError) as exc:
        raise RuntimeError(f"dashboard preflight failed: {exc}") from exc
    mode_values = parse_reply_values(mode_reply)
    dashboard_mode = int(mode_values[0]) if mode_values else None
    if args.enable_robot and dashboard_mode != 5:
        print(f"EnableRobot(): dashboard_mode={dashboard_mode}; enabling robot", flush=True)
        reply = dashboard.command("EnableRobot()", timeout=3.0, expect_zero=False, allow_empty=True)
        if reply:
            print(f"EnableRobot reply: {reply}", flush=True)
            code = parse_reply_code(reply)
            if code != 0:
                raise RuntimeError(f"EnableRobot() failed: {reply}")
        deadline = time.monotonic() + args.enable_timeout_sec
        last_reply = ""
        while time.monotonic() < deadline:
            time.sleep(0.2)
            last_reply = dashboard.command("RobotMode()", timeout=1.5, expect_zero=True)
            values = parse_reply_values(last_reply)
            mode = int(values[0]) if values else None
            if mode == 5:
                print(f"RobotMode after enable: {last_reply}", flush=True)
                break
        else:
            print(f"RobotMode after EnableRobot() did not become 5: {last_reply}", flush=True)
    dashboard.command(f"SpeedFactor({int(args.speed)})", timeout=1.5, expect_zero=True)


def format_pose(pose: list[float]) -> str:
    return "[" + ", ".join(f"{float(value):.4f}" for value in pose) + "]"


def move_to_pose(
    dashboard: Dashboard,
    feedback: FeedbackReader,
    pose: list[float],
    command_name: str,
    label: str,
    args,
    guarded: bool = True,
) -> tuple[str, dict | None]:
    if guarded and feedback.snapshot(args.max_feedback_age_sec)["di1"]:
        raise RuntimeError(f"DI1 is triggered before moving to {label}")
    dashboard.command(pose_command(command_name, pose), timeout=args.command_timeout_sec, expect_zero=True)
    deadline = time.monotonic() + args.positioning_timeout_sec
    last_report = 0.0
    while time.monotonic() < deadline:
        snapshot = feedback.snapshot(args.max_feedback_age_sec)
        if guarded and snapshot["di1"]:
            dashboard.stop()
            stop_snapshot = feedback.snapshot(args.max_feedback_age_sec)
            print(f"  EARLY_TRIGGER while moving to {label}; stopped at {format_pose(stop_snapshot['pose'])}", flush=True)
            return "EARLY_TRIGGER", stop_snapshot
        if pose_reached(
            snapshot["pose"],
            pose,
            args.position_tolerance_mm,
            args.orientation_tolerance_deg,
        ):
            return "REACHED", snapshot
        now = time.monotonic()
        if args.verbose_motion and now - last_report >= 1.0:
            pos_err, ori_err = pose_errors(snapshot["pose"], pose)
            print(f"  moving {label}: pos_err={pos_err:.3f}mm ori_err={ori_err:.3f}deg", flush=True)
            last_report = now
        time.sleep(args.poll_interval_sec)
    dashboard.stop()
    snapshot = feedback.snapshot(args.max_feedback_age_sec)
    pos_err, ori_err = pose_errors(snapshot["pose"], pose)
    raise TimeoutError(
        f"timeout moving to {label}; pos_err={pos_err:.4f}mm ori_err={ori_err:.4f}deg "
        f"current={format_pose(snapshot['pose'])} target={format_pose(pose)}"
    )


def probe_to_target(dashboard: Dashboard, feedback: FeedbackReader, item: dict, args) -> tuple[str, dict | None, dict]:
    if feedback.snapshot(args.max_feedback_age_sec)["di1"]:
        raise RuntimeError(f"DI1 is triggered at probe start {item['plan_id']}")
    dashboard.command(pose_command("MovL", item["target_pose"]), timeout=args.command_timeout_sec, expect_zero=True)
    deadline = time.monotonic() + args.timeout_sec
    trigger_snapshot = None
    while time.monotonic() < deadline:
        snapshot = feedback.snapshot(args.max_feedback_age_sec)
        if snapshot["di1"]:
            trigger_snapshot = snapshot
            dashboard.stop()
            stop_snapshot = feedback.snapshot(args.max_feedback_age_sec)
            return "HIT", trigger_snapshot, stop_snapshot
        if pose_reached(
            snapshot["pose"],
            item["target_pose"],
            args.position_tolerance_mm,
            args.orientation_tolerance_deg,
        ):
            break
        time.sleep(args.poll_interval_sec)
    stop_snapshot = feedback.snapshot(args.max_feedback_age_sec)
    return "MISS", None, stop_snapshot


def execute_item(dashboard: Dashboard, feedback: FeedbackReader, args, item: dict) -> str:
    plan_id = item["plan_id"]
    print(f"\n{plan_id} branch={item['branch']}", flush=True)
    print(f"  safe       {format_pose(item['safe_pose'])}", flush=True)
    print(f"  transition {format_pose(item['transition_pose'])}", flush=True)
    print(f"  start      {format_pose(item['start_pose'])}", flush=True)
    print(f"  target     {format_pose(item['target_pose'])}", flush=True)

    if args.execute:
        status, snapshot = move_to_pose(dashboard, feedback, item["safe_pose"], args.safe_move, f"safe {plan_id}", args)
        if status == "EARLY_TRIGGER":
            append_stable_row(args.output, contact_row(args, item, "EARLY_TRIGGER_SAFE", snapshot, snapshot))
            return "EARLY_TRIGGER_SAFE"

        status, snapshot = move_to_pose(
            dashboard,
            feedback,
            item["transition_pose"],
            args.transition_move,
            f"transition {plan_id}",
            args,
        )
        if status == "EARLY_TRIGGER":
            append_stable_row(args.output, contact_row(args, item, "EARLY_TRIGGER_TRANSITION", snapshot, snapshot))
            return "EARLY_TRIGGER_TRANSITION"

        status, snapshot = move_to_pose(
            dashboard,
            feedback,
            item["start_pose"],
            "MovL",
            f"start {plan_id}",
            args,
        )
        if status == "EARLY_TRIGGER":
            append_stable_row(args.output, contact_row(args, item, "EARLY_TRIGGER_START", snapshot, snapshot))
            return "EARLY_TRIGGER_START"

        status, trigger, stop_snapshot = probe_to_target(dashboard, feedback, item, args)
        append_stable_row(args.output, contact_row(args, item, status, trigger, stop_snapshot))
        print(f"  {status}", flush=True)

        move_to_pose(
            dashboard,
            feedback,
            item["transition_pose"],
            "MovL",
            f"retract transition {plan_id}",
            args,
            guarded=False,
        )
        if feedback.snapshot(args.max_feedback_age_sec)["di1"]:
            raise RuntimeError(f"DI1 remains triggered after retracting {plan_id}")
        if args.return_safe_after_each_sample:
            move_to_pose(dashboard, feedback, item["safe_pose"], args.safe_move, f"safe after {plan_id}", args)
        return status

    print("  dry-run: no motion", flush=True)
    return "DRY_RUN"


def selected_items(plan: list[dict], args) -> list[dict]:
    rows = plan
    if args.branches:
        branches = set(args.branches)
        rows = [item for item in rows if item["branch"] in branches]
    if args.start_index is not None:
        start = max(1, args.start_index)
        rows = rows[start - 1 :]
    if args.end_index is not None:
        rows = rows[: max(0, args.end_index - (args.start_index or 1) + 1)]
    if args.max_samples is not None:
        rows = rows[: args.max_samples]
    if args.resume:
        done = existing_plan_ids(args.output)
        rows = [item for item in rows if item["plan_id"] not in done]
    return rows


